"""Export the service-area CSVs to data/service-areas.json for the website.

Usage:  python export_site_json.py   (run after build_area_lists.py)

The site shows areas grouped and collapsible, so groups are tidied for display:
- single-sector groups (F-7, G-13, ...) and the sector grid merge into one "Sectors" group
- "Various ..." groups get readable names
- far tehsils are flagged `outlying`: the one-hour delivery target is not promised there
Only area names are exported (no sources or notes), sorted A-Z within each group.
"""
import csv
import json
import os
import re
from collections import defaultdict

HERE = os.path.dirname(os.path.abspath(__file__))
OUT = os.path.join(HERE, "..", "..", "..", "data", "service-areas.json")

OUTLYING = {"Gujar Khan / Daultala", "Kallar Syedan", "Taxila / Wah", "Kahuta", "Adiala / Dhamial / Chakri"}
RENAME = {
    "Islamabad sector grid": "Sectors and sub-sectors",
    "Islamabad": "Markets, markaz and main roads",
    "Various Islamabad villages/towns": "Villages and towns",
    "Various ICT localities": "Other ICT localities",
    "Various ICT zones": "Housing schemes",
    "Various": "Other housing schemes",
    "City / peripheral Islamabad": "Peripheral Islamabad",
    "Rawalpindi-Islamabad metro": "DHA, Nova City and expressway schemes",
    "DHA Islamabad-Rawalpindi": "DHA sectors",
    "Major road corridors": "Main roads and junctions",
    "Other housing societies": "Housing societies",
}
SECTOR_GROUP = re.compile(r"^[A-I]-\d+$")


def display_group(city, group):
    if SECTOR_GROUP.match(group) or group == "Islamabad sector grid":
        return "Sectors and sub-sectors"
    if city == "rawalpindi" and group == "Various ICT zones":
        return "Bahria Town Rawalpindi"
    return RENAME.get(group, group)


def build(city):
    groups = defaultdict(set)
    flags = {}
    with open(os.path.join(HERE, f"{city}_areas.csv"), encoding="utf-8-sig") as f:
        for row in csv.DictReader(f):
            g = display_group(city, row["Group"])
            groups[g].add(row["Area"].strip())
            flags[g] = row["Group"] in OUTLYING
    ordered = sorted(groups, key=lambda g: (flags[g], g != "Sectors and sub-sectors", -len(groups[g]), g))
    natural = lambda s: [int(t) if t.isdigit() else t.lower() for t in re.split(r"(\d+)", s)]
    return {
        "count": sum(len(v) for v in groups.values()),
        "groups": [{"name": g, "outlying": flags[g], "areas": sorted(groups[g], key=natural)} for g in ordered],
    }


def main():
    data = {
        "_readme": "Generated by docs/content-plan/service-areas/export_site_json.py from the owner-confirmed area lists "
                   "(30 Oct 2026). Do not edit by hand: change the CSVs or OVERRIDES in build_area_lists.py and re-run both scripts.",
        "islamabad": build("islamabad"),
        "rawalpindi": build("rawalpindi"),
    }
    with open(OUT, "w", encoding="utf-8") as f:
        json.dump(data, f, ensure_ascii=False, indent=1)
        f.write("\n")
    for c in ("islamabad", "rawalpindi"):
        print(c, data[c]["count"], "areas in", len(data[c]["groups"]), "groups:",
              ", ".join(f"{g['name']} ({len(g['areas'])}{', outlying' if g['outlying'] else ''})" for g in data[c]["groups"]))


if __name__ == "__main__":
    main()
